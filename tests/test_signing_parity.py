"""Byte-for-byte EIP-712 parity with the Rust signer.

The vectors are generated by Hypercall's Rust signer, whose CI fails if
they go stale. Each case rebuilds the signed message from the
wire request alone, so it proves the JSON we send and the bytes we sign agree
with the SDK the server is tested against.
"""

import base64
import json
from pathlib import Path

import pytest
from eth_account import Account

from hypercall_rfq_example import signing

VECTORS = json.loads((Path(__file__).parent / "golden" / "rfq_v2_signing_vectors.json").read_text())
KEY = VECTORS["private_key"]
CHAIN = VECTORS["chain_id"]


def message_for(vector: dict) -> dict:
    request = vector["request"]
    match vector["primary_type"]:
        case "AuthorizeRfqQuoteV2":
            return signing.firm_quote_message(request["terms"], request["nonce"])
        case "DeclineRfqV2":
            return signing.decline_message(vector["rfq_id"], request)
        case "InvalidateRfqV2":
            return signing.withdraw_quote_message(vector["rfq_id"], vector["quote_id"], request)
        case "BulkWithdrawRfqV2":
            return signing.bulk_withdrawal_message(request)
        case "ScheduleRfqQuoteCancelV2":
            return signing.cancel_schedule_message(request)
        case "AuthorizeRfqReadV2":
            return signing.read_grant_message(
                request["account"], request["issued_at_ms"], request["expires_at_ms"], request["nonce"]
            )
        case "HLOrder":
            return signing.perp_order_message(request)
    raise AssertionError(vector["primary_type"])


@pytest.mark.parametrize("vector", VECTORS["signing"], ids=lambda v: v["name"])
def test_signature_matches_rust(vector):
    domain = vector.get("domain", "Hypercall")
    message = message_for(vector)
    if "digest" in vector:
        assert "0x" + signing.digest(vector["primary_type"], message, CHAIN, domain).hex() == vector["digest"]
    assert signing.sign(vector["primary_type"], message, KEY, CHAIN, domain) == vector["signature"]


def test_vectors_cover_every_maker_message():
    covered = {v["primary_type"] for v in VECTORS["signing"]}
    assert covered == set(signing.TYPES)


def test_signer_is_the_vector_key():
    assert Account.from_key(KEY).address.lower() == VECTORS["signer"]


def test_read_grant_bearer_decodes_to_the_signed_grant():
    vector = next(v for v in VECTORS["signing"] if v["name"] == "read_grant")
    padded = vector["bearer"] + "=" * (-len(vector["bearer"]) % 4)
    assert json.loads(base64.urlsafe_b64decode(padded)) == vector["request"]


@pytest.mark.parametrize("case", VECTORS["premium"])
def test_reference_premium_matches_rust(case):
    step = int(case["step"]) if case["step"] else None
    got = signing.reference_premium(
        case["legs"], [int(p) for p in case["prices_micros"]], int(case["reference_quantity"]), step
    )
    expected = None if case["result"] is None else (case["result"][0], int(case["result"][1]))
    assert got == expected
